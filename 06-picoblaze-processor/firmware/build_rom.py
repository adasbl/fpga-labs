"""Assemble the instruction subset used by counter.psm into a synchronous ROM.

Opcode reference: https://github.com/kevinpt/opbasm/blob/master/opbasm/devices.py
For larger programs use the full KCPSM6 assembler or opbasm (-6).
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "firmware/counter.psm"
TARGET = ROOT / "06-picoblaze-processor.srcs/sources_1/new/counter_rom.vhd"
OPCODES = {"load": 0x01000, "input": 0x09000, "output": 0x2D000,
           "and": 0x03000, "xor": 0x07000, "compare": 0x1D000,
           "add": 0x11000, "sub": 0x19000}


def assemble():
    labels, statements = {}, []
    for number, raw in enumerate(SOURCE.read_text().splitlines(), 1):
        line = raw.split(";", 1)[0].strip().lower()
        if ":" in line:
            label, line = line.split(":", 1)
            if label in labels:
                raise ValueError(f"Line {number}: duplicate label {label}")
            labels[label] = len(statements)
            line = line.strip()
        if line:
            statements.append((number, line))
    words = []
    for number, line in statements:
        fields = re.split(r"[\s,]+", line)
        op, args = fields[0], fields[1:]
        if op == "jump":
            if len(args) == 1:
                code = 0x22000
            elif len(args) == 2 and args[0] in ("z", "nz"):
                code = 0x22000 + {"z": 0x10000, "nz": 0x14000}[args[0]]
            else:
                raise ValueError(f"Line {number}: unsupported jump {line}")
            code |= labels[args[-1]]
        elif op in OPCODES and len(args) == 2 and re.fullmatch(r"s[0-9a-f]", args[0]):
            code = OPCODES[op] | (int(args[0][1], 16) << 8)
            if re.fullmatch(r"s[0-9a-f]", args[1]) and op not in ("input", "output"):
                code = (code - 0x1000) | (int(args[1][1], 16) << 4)
            else:
                value = int(args[1], 16)
                if not 0 <= value <= 255:
                    raise ValueError(f"Line {number}: byte out of range")
                code |= value
        else:
            raise ValueError(f"Line {number}: unsupported instruction {line}")
        words.append((code, line))
    return words


def main():
    words = assemble()
    entries = "\n".join(f'        {i} => "{code:018b}", -- {line}'
                        for i, (code, line) in enumerate(words))
    TARGET.write_text('''-- Generated by firmware/build_rom.py from firmware/counter.psm. Do not edit.
library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

entity counter_rom is
    port (clk, enable : in std_logic;
          address : in std_logic_vector(11 downto 0);
          instruction : out std_logic_vector(17 downto 0));
end entity;

architecture rtl of counter_rom is
    type rom_t is array (0 to 4095) of std_logic_vector(17 downto 0);
    constant ROM : rom_t := (
''' + entries + '''
        others => "100010000000000000" -- jump 000
    );
begin
    process(clk)
    begin
        if rising_edge(clk) then
            if enable = '1' then
                instruction <= ROM(to_integer(unsigned(address)));
            end if;
        end if;
    end process;
end architecture;
''', encoding="ascii")
    print(f"Generated {TARGET.name}: {len(words)} instructions")


if __name__ == "__main__":
    main()
